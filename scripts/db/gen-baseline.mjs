#!/usr/bin/env node
// Generates the baseline migration (prisma/migrations/0001_baseline/migration.sql) from
// prisma/schema.prisma. Prisma's schema engine cannot run in every environment (it is downloaded
// from binaries.prisma.sh), so this script produces the same DDL shape Prisma uses for PostgreSQL:
// the same identifier quoting, constraint names (Model_pkey, Model_col_key, Model_a_b_idx,
// Model_col_fkey) and default referential actions.
//
// It fails on any schema feature it does not understand, so unsupported syntax cannot be dropped
// silently. CI checks the result against the schema with `prisma migrate diff`.
//
// Usage: node scripts/db/gen-baseline.mjs [--check]
//   --check  exit 1 if the committed migration differs from what would be generated.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const schemaPath = join(root, 'prisma', 'schema.prisma');
const outPath = join(root, 'prisma', 'migrations', '0001_baseline', 'migration.sql');

export function stripComments(text) {
  // Remove // comments that are not inside a string literal.
  return text
    .split('\n')
    .map((line) => {
      let inString = false;
      for (let i = 0; i < line.length; i++) {
        const ch = line[i];
        if (ch === '"' && line[i - 1] !== '\\') inString = !inString;
        if (!inString && ch === '/' && line[i + 1] === '/') return line.slice(0, i).replace(/\s+$/, '');
      }
      return line;
    })
    .join('\n');
}

// Splits "@a(x) @b @c(y(z))" into [{ name: 'a', args: 'x' }, ...], honouring nested parentheses.
export function parseAttributes(text) {
  const out = [];
  let i = 0;
  while (i < text.length) {
    if (text[i] !== '@') {
      i++;
      continue;
    }
    let j = i + 1;
    while (j < text.length && /[\w.]/.test(text[j])) j++;
    const name = text.slice(i + 1, j);
    let args = null;
    if (text[j] === '(') {
      let depth = 0;
      let k = j;
      let inString = false;
      for (; k < text.length; k++) {
        const ch = text[k];
        if (ch === '"' && text[k - 1] !== '\\') inString = !inString;
        if (inString) continue;
        if (ch === '(') depth++;
        if (ch === ')') {
          depth--;
          if (depth === 0) break;
        }
      }
      if (depth !== 0) throw new Error(`Unbalanced parentheses in attribute @${name}`);
      args = text.slice(j + 1, k);
      j = k + 1;
    }
    out.push({ name, args });
    i = j;
  }
  return out;
}

const q = (identifier) => `"${identifier}"`;

function splitList(text) {
  return text
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean);
}

function sqlStringLiteral(value) {
  return `'${value.replace(/'/g, "''")}'`;
}

function parseDefault(raw, field) {
  const value = raw.trim();
  if (value === 'uuid()' || value === 'cuid()') return null; // generated by the Prisma client, not the DB
  if (value === 'now()') return 'CURRENT_TIMESTAMP';
  if (/^\w+\(.*\)$/.test(value)) throw new Error(`${field.model}.${field.name}: unsupported default ${value}`);
  if (value.startsWith('"')) {
    const inner = value.slice(1, -1);
    if (field.type === 'Json') return `${sqlStringLiteral(inner)}`;
    return sqlStringLiteral(inner);
  }
  if (value === 'true' || value === 'false') return value.toUpperCase();
  if (/^-?\d+(\.\d+)?$/.test(value)) return value;
  if (value === '[]') return sqlStringLiteral('[]');
  if (/^[A-Z_][A-Z0-9_]*$/.test(value) && enumNames.has(field.type)) return sqlStringLiteral(value);
  throw new Error(`${field.model}.${field.name}: unsupported default ${value}`);
}

function columnType(field) {
  const native = field.native;
  const t = field.type;
  if (enumNames.has(t)) return q(t);
  if (t === 'String') {
    if (!native) return 'TEXT';
    if (native.name === 'Uuid') return 'UUID';
    if (native.name === 'Text') return 'TEXT';
    if (native.name === 'VarChar') return `VARCHAR(${native.args})`;
    if (native.name === 'Char') return `CHAR(${native.args})`;
    throw new Error(`${field.model}.${field.name}: unsupported native type @db.${native.name}`);
  }
  if (t === 'Int') return 'INTEGER';
  if (t === 'BigInt') return 'BIGINT';
  if (t === 'Boolean') return 'BOOLEAN';
  if (t === 'Float') return 'DOUBLE PRECISION';
  if (t === 'Json') return 'JSONB';
  if (t === 'DateTime') {
    if (!native) return 'TIMESTAMP(3)';
    if (native.name !== 'Timestamptz') throw new Error(`${field.model}.${field.name}: unsupported @db.${native.name}`);
    return `TIMESTAMPTZ(${native.args ?? 6})`;
  }
  throw new Error(`${field.model}.${field.name}: unsupported type ${t}`);
}

let enumNames = new Set();
let modelNames = new Set();

export function parseSchema(source) {
  const text = stripComments(source);
  const enums = [];
  const models = [];

  for (const m of text.matchAll(/^(model|enum)\s+(\w+)\s*\{([\s\S]*?)^\}/gm)) {
    const [, kind, name, body] = m;
    if (kind === 'enum') {
      enums.push({
        name,
        values: body
          .split('\n')
          .map((l) => l.trim())
          .filter((l) => l && !l.startsWith('@')),
      });
    } else {
      models.push({ name, body });
    }
  }

  enumNames = new Set(enums.map((e) => e.name));
  modelNames = new Set(models.map((m) => m.name));

  return {
    enums,
    models: models.map((m) => parseModel(m)),
  };
}

function parseModel({ name, body }) {
  const fields = [];
  const blockAttrs = [];
  for (const rawLine of body.split('\n')) {
    const line = rawLine.trim();
    if (!line) continue;
    if (line.startsWith('@@')) {
      blockAttrs.push(line);
      continue;
    }
    const m = line.match(/^(\w+)\s+(\w+)(\[\])?(\?)?(?:\s+(.*))?$/);
    if (!m) throw new Error(`${name}: cannot parse line "${line}"`);
    const [, fieldName, type, isList, isOptional, rest = ''] = m;
    const attrs = parseAttributes(rest);
    const field = {
      model: name,
      name: fieldName,
      type,
      isList: !!isList,
      optional: !!isOptional,
      attrs,
      native: null,
      isId: false,
      isUnique: false,
      isUpdatedAt: false,
      def: undefined,
      relation: null,
    };
    for (const a of attrs) {
      if (a.name.startsWith('db.')) field.native = { name: a.name.slice(3), args: a.args };
      else if (a.name === 'id') field.isId = true;
      else if (a.name === 'unique') field.isUnique = true;
      else if (a.name === 'updatedAt') field.isUpdatedAt = true;
      else if (a.name === 'default') field.default = a.args;
      else if (a.name === 'relation') field.relation = parseRelationArgs(a.args ?? '', name, fieldName);
      else throw new Error(`${name}.${fieldName}: unsupported attribute @${a.name}`);
    }
    fields.push(field);
  }

  const blocks = blockAttrs.map((line) => {
    const mm = line.match(/^@@(\w+)\(\s*\[([^\]]*)\]\s*\)\s*$/);
    if (!mm) throw new Error(`${name}: unsupported block attribute "${line}"`);
    return { kind: mm[1], fields: splitList(mm[2]) };
  });

  return { name, fields, blocks };
}

function parseRelationArgs(args, model, field) {
  const fields = args.match(/fields:\s*\[([^\]]*)\]/);
  const refs = args.match(/references:\s*\[([^\]]*)\]/);
  const onDelete = args.match(/onDelete:\s*(\w+)/);
  const onUpdate = args.match(/onUpdate:\s*(\w+)/);
  const known = /^(fields|references|onDelete|onUpdate|name)\s*:/;
  for (const part of args.split(/,(?![^\[]*\])/).map((s) => s.trim()).filter(Boolean)) {
    // A bare quoted string is the relation name (e.g. @relation("CategoryTree", ...)). It does not affect SQL.
    if (/^"[^"]*"$/.test(part)) continue;
    if (!known.test(part)) throw new Error(`${model}.${field}: unsupported @relation argument "${part}"`);
  }
  return {
    fields: fields ? splitList(fields[1]) : null,
    references: refs ? splitList(refs[1]) : null,
    onDelete: onDelete ? onDelete[1] : null,
    onUpdate: onUpdate ? onUpdate[1] : null,
  };
}

// A relation list (for example Category.products) must be the back-reference of a singular relation
// that declares `fields` on the other model. Implicit many-to-many relations would need join tables,
// which this generator does not produce. They are rejected rather than silently skipped.
function checkListRelation(parsed, model, field) {
  const target = parsed.models.find((m) => m.name === field.type);
  const owner = target.fields.find(
    (f) => f.type === model.name && f.relation && f.relation.fields && !f.isList,
  );
  if (!owner) {
    throw new Error(`${model.name}.${field.name}: implicit many-to-many relations are not supported by gen-baseline`);
  }
}

// Prisma's default referential actions when none are given.
function defaultOnDelete(field) {
  return field.optional ? 'SetNull' : 'Restrict';
}

const SQL_ACTIONS = { Cascade: 'CASCADE', Restrict: 'RESTRICT', SetNull: 'SET NULL', NoAction: 'NO ACTION', SetDefault: 'SET DEFAULT' };

export function generateSql(parsed) {
  const out = [];
  out.push('-- Baseline schema generated from prisma/schema.prisma by scripts/db/gen-baseline.mjs.');
  out.push('-- Do not edit by hand. Hand-written constraints live in later migrations.');
  out.push('');

  for (const e of parsed.enums) {
    out.push(`CREATE TYPE ${q(e.name)} AS ENUM (${e.values.map(sqlStringLiteral).join(', ')});`);
  }
  if (parsed.enums.length) out.push('');

  const tailStatements = [];

  for (const model of parsed.models) {
    const cols = [];
    const constraints = [];
    const indexes = [];
    for (const f of model.fields) {
      if (modelNames.has(f.type)) {
        // Relation fields: only the owning side has a column. Lists are back-references, checked below.
        if (f.isList) checkListRelation(parsed, model, f);
        continue;
      }
      if (f.isList) {
        // Scalar list, e.g. tags String[] -> TEXT[]. Only String lists are supported.
        if (f.type !== 'String' || f.optional) throw new Error(`${model.name}.${f.name}: unsupported list type ${f.type}[]`);
        if (f.default !== undefined && f.default.trim() !== '[]') {
          throw new Error(`${model.name}.${f.name}: unsupported list default ${f.default}`);
        }
        cols.push(`${q(f.name)} TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[]`);
        continue;
      }
      const parts = [q(f.name), columnType(f)];
      parts.push(f.optional ? '' : 'NOT NULL');
      if (f.default !== undefined) {
        const dflt = parseDefault(f.default, f);
        if (dflt !== null) parts.push(`DEFAULT ${dflt}`);
      }
      cols.push(parts.filter(Boolean).join(' '));
    }

    const idFields = [
      ...model.fields.filter((f) => f.isId).map((f) => f.name),
      ...model.blocks.filter((b) => b.kind === 'id').flatMap((b) => b.fields),
    ];
    if (idFields.length === 0) throw new Error(`${model.name}: no primary key`);
    constraints.push(`CONSTRAINT ${q(`${model.name}_pkey`)} PRIMARY KEY (${idFields.map(q).join(', ')})`);

    out.push(`CREATE TABLE ${q(model.name)} (`);
    out.push(cols.concat(constraints).map((c) => `    ${c}`).join(',\n'));
    out.push(');');

    for (const f of model.fields) {
      if (f.isUnique) indexes.push(`CREATE UNIQUE INDEX ${q(`${model.name}_${f.name}_key`)} ON ${q(model.name)}(${q(f.name)});`);
    }
    for (const b of model.blocks) {
      if (b.kind === 'unique') {
        indexes.push(`CREATE UNIQUE INDEX ${q(`${model.name}_${b.fields.join('_')}_key`)} ON ${q(model.name)}(${b.fields.map(q).join(', ')});`);
      } else if (b.kind === 'index') {
        indexes.push(`CREATE INDEX ${q(`${model.name}_${b.fields.join('_')}_idx`)} ON ${q(model.name)}(${b.fields.map(q).join(', ')});`);
      } else if (b.kind !== 'id') {
        throw new Error(`${model.name}: unsupported block attribute @@${b.kind}`);
      }
    }
    if (indexes.length) out.push(...indexes);
    out.push('');

    for (const f of model.fields) {
      // Only the side that declares `fields` owns the foreign key. The other side is a back-reference.
      if (!f.relation || !f.relation.fields) continue;
      const rel = f.relation;
      const localFields = rel.fields ?? [];
      const target = parsed.models.find((m) => m.name === f.type);
      if (!target) throw new Error(`${model.name}.${f.name}: relation target ${f.type} not found`);
      const refFields = rel.references ?? [];
      const onDelete = SQL_ACTIONS[rel.onDelete ?? defaultOnDelete(f)];
      const onUpdate = SQL_ACTIONS[rel.onUpdate ?? 'Cascade'];
      if (!onDelete || !onUpdate) throw new Error(`${model.name}.${f.name}: unsupported referential action`);
      const constraintName = `${model.name}_${localFields.join('_')}_fkey`;
      tailStatements.push(
        `ALTER TABLE ${q(model.name)} ADD CONSTRAINT ${q(constraintName)} FOREIGN KEY (${localFields.map(q).join(', ')}) REFERENCES ${q(target.name)}(${refFields.map(q).join(', ')}) ON DELETE ${onDelete} ON UPDATE ${onUpdate};`,
      );
    }
  }

  if (tailStatements.length) {
    out.push('-- Foreign keys');
    out.push(...tailStatements);
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').replace(/\n+$/, '\n');
}

function main() {
  const check = process.argv.includes('--check');
  const parsed = parseSchema(readFileSync(schemaPath, 'utf8'));
  const sql = generateSql(parsed);
  if (check) {
    const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
    if (current !== sql) {
      console.error(`${outPath} is out of date. Run: node scripts/db/gen-baseline.mjs`);
      process.exit(1);
    }
    console.log('baseline migration is up to date');
    return;
  }
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, sql);
  console.log(`wrote ${outPath}: ${parsed.models.length} tables, ${parsed.enums.length} enums`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
